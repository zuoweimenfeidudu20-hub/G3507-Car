/**
 * @brief 循线增量/位置式转向 PID 控制
 */
static int 计算灰度循线PID转向纠偏量(int 偏差)
{
    static int 上次偏差 = 0;
    float Kp = 0.008f;
    float Kd = 0.002f;

    int 纠偏输出 = (int)(Kp * (float)偏差 + Kd * (float)(偏差 - 上次偏差));
    上次偏差 = 偏差;

    /* 转向限幅, 保护电机差速不过大 */
    if (纠偏输出 > 15)  纠偏输出 = 15;
    if (纠偏输出 < -15) 纠偏输出 = -15;

    return 纠偏输出;
}

