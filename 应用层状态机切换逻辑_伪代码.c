#define 目标巡航速度_PWM                  (35)       /* 发车时直接下发35% PWM目标 */


#define 楼梯岔路前盲区屏蔽里程_CM          (80.0f)    /* 从起点出发前80cm绝不可能到楼梯, 强制屏蔽分支识别 */
#define 楼梯岔路物理判定区间_CM          (25.0f)    /* 楼梯分岔口识别窗口长度 */
#define 楼梯单圈标准周长_CM              (115.0f)   /* 楼梯内圈单圈物理长度标定值 */
#define 楼梯单圈里程允许误差_CM          (20.0f)    /* 示意常规窗口 [95cm,135cm]，以实测标定 */
#define 楼梯单圈扩展误差_CM              (40.0f)    /* IMU有效且路标明确时的扩展窗口 */
#define 楼梯单圈航向允许误差_DEG         (60.0f)    /* 本圈连续转角约360°的示意容差 */

#define 楼梯岔口后至上方直道_CM          (55.0f)    /* 从通过岔口后到左上弯的相对里程示例，待实车标定 */
#define 楼梯出口至上方直道_CM            (20.0f)    /* 上方合流口到左上弯的参考里程，待实车标定 */
#define 上方直道总长度_CM                (160.0f)   /* 上方长直道总长 */
#define 避障触发安全距离_CM              (25.0f)    /* 超声波前向测距小于该距离触发避障绕行 */

#define 赛道全程参考总里程_CM            (450.0f)   /* 绕场一周的总物理长度 */
#define 减速进站准备里程门限_CM          (400.0f)   /* 跑完400cm后开启终点线检测与平缓减速 */

/* ========================================================================== */
/*                           二、 状态机枚举体系定义                          */
/* ========================================================================== */

/**
 * @brief 【顶层】应用层大任务模式 (由按键 Key1~Key4 或 OLED 菜单选择)
 */
typedef enum {
    任务_空闲待机 = 0,
    任务1_全程匀速循线避障,
    任务2_楼梯区域闭环跑满两圈,
    任务3_上方长直道正弦摆动走直线,
    任务4_车顶指向标实时对准信标点
} 应用层任务模式_e;

/**
 * @brief 【中层】赛道拓扑空间导航主区间 (依赖里程计与地图特征)
 */
typedef enum {
    区间_起点直接启动 = 0,        /* 起点出发时直接下发35% PWM */
    区间_楼梯前盲区屏蔽,          /* 正常巡线, 强制屏蔽楼梯分岔误判 */
    区间_楼梯分岔决策口,          /* 顺时针上行遇到右侧入口: 任务1/3直行, 任务2右转入楼梯 */
    区间_楼梯环形闭环多圈,        /* 任务2专属: 跑满整整两圈的闭环区 */
    区间_左侧主道继续上行,        /* 通过楼梯岔口/出口后，沿左侧竖道到左上弯 */
    区间_上方长直道,              /* 任务1避障 / 任务3正弦摆动 / 任务2常规通过 */
    区间_终点减速回站,            /* 绕场完成前平稳匀减速, 准备找终点线 */
    区间_停起点驻车完成,          /* 精准停靠在起点停车方框内, 自动锁电机刹车 */
    区间_定位异常安全停机         /* 超过扩展搜索窗口仍未确认路标，停机排查 */
} 赛道导航区间_e;

/**
 * @brief 【底层子状态机】楼梯跑满两圈闭环计数状态
 */
typedef enum {
    楼梯子状态_进入后第1圈循迹 = 0,
    楼梯子状态_第1圈完成判定,
    楼梯子状态_第2圈循迹中,
    楼梯子状态_第2圈完成确认,
    楼梯子状态_右切并回主干道     /* 从上方合流口右转，沿主道继续向上 */
} 楼梯闭环子状态_e;

/**
 * @brief 【底层子状态机】上方直道超声波避障四段式绕行状态
 */
typedef enum {
    避障子状态_直道正常循线 = 0,
    避障子状态_左打角脱线绕出,    /* 陀螺仪向左偏转35°脱离黑线 */
    避障子状态_平行越障前行,      /* 平行于障碍物行驶避开障碍物理区 */
    避障子状态_右打角对准回线,    /* 陀螺仪向右偏转对准原赛道黑线 */
    避障子状态_重新锁线平稳恢复    /* 灰度中心传感器再次咬住黑线, 退出避障 */
} 避障动作子状态_e;

/**
 * @brief 灰度传感器路况特征分类
 */
typedef enum {
    路况_普通直线缓弯 = 0,
    路况_左侧有分支黑线,          /* 楼梯环路回到下方岔口时的内侧支线特征 */
    路况_右侧有分支黑线,          /* 顺时针上行的楼梯入口，以及环路上方出口特征 */
    路况_检测到全黑起终点线,
    路况_完全脱轨丢线
} 灰度路况特征_e;

/* ========================================================================== */
/*                           三、 导航状态机核心上下文结构体                    */
/* ========================================================================== */

typedef struct {
    应用层任务模式_e    当前任务;
    赛道导航区间_e      当前导航区间;
    
    /* 计时与里程统计 */
    float              当前区间起始基准里程_CM;
    uint32_t           当前区间已驻留时间_MS;
    float              小车全程累计总里程_CM;
    float              小车当前航向偏航角_DEG;      /* 陀螺仪实时偏航角 (-180°~+180°) */

    /* 任务2：楼梯两圈闭环仲裁专用变量 */
    楼梯闭环子状态_e    楼梯子状态;
    uint8_t            楼梯已跑完圈数;             /* 目标值必须达到2 */
    float              楼梯区间起始偏航基准角_DEG;
    float              楼梯区间累计转角_DEG;       /* 连续积分, 跑完2圈应接近 720° */
    float              楼梯单圈起始里程_CM;
    float              楼梯单圈起始累计角_DEG;     /* 每圈重新建立航向参考，避免前圈误差累计 */
    bool               楼梯计圈路标已锁存;         /* 离开路标后才允许下一次计数 */

    /* 任务1：避障专属变量 */
    避障动作子状态_e    避障子状态;
    float              避障起始偏航基准角_DEG;
    float              避障起始里程_CM;

    /* 任务3：正弦走直线专属变量 */
    float              正弦摆动时间相位_RAD;

    /* 任务4：车顶指向标瞄准控制 */
    float              车顶舵机目标角度_DEG;
} 小车全景导航上下文_t;

/* 全局单例上下文 */
static 小车全景导航上下文_t 小车控制上下文;

/* ========================================================================== */
/*                           四、 底层与传感器交互接口 (伪声明)                */
/* ========================================================================== */

/* 传感器采集与位姿感知 */
extern float 读取编码器双轮平均行驶里程_CM(void);
extern float 读取陀螺仪当前绝对偏航角_DEG(void);
extern bool 陀螺仪数据有效(void); /* 根据新样本时间戳判断，不能反复使用旧角度 */
extern float 读取超声波前方障碍物距离_CM(void);
extern 灰度路况特征_e 扫描8路灰度传感器路面特征(int *当前横向加权偏差);
extern 应用层任务模式_e 读取按键与菜单选定任务(void);

/* 电机执行与运动底层：允许转弯/避障时按需要调整速度，不强制双轮平均值恒定。 */
extern void 设置左右双轮目标速度(int 基准速度, int 差速纠偏量);
extern void 紧急刹车完全停机(void);
extern void 设置车顶指向标舵机指向绝对角度(float 目标绝对角度_DEG);

/* 上位机无线遥测通信 */
extern void 上位机无线遥测_发送运行波形与状态(float 左右轮平均速度, uint32_t 运行时间_MS, uint8_t 任务编号, uint8_t 当前区间);

/* 局部算法工具函数 */
static int 计算灰度循线PID转向纠偏量(int 偏差);
static bool 楼梯单圈路标可信(小车全景导航上下文_t *ctx, 灰度路况特征_e 路况, float 本圈里程_CM);
static void 解算并更新车顶指向标瞄准信标角度(小车全景导航上下文_t *ctx);

/* ========================================================================== */
/*                           五、 核心应用层状态机切换调度主逻辑               */
/* ========================================================================== */

/**
 * @brief 应用层导航状态机单步周期轮询 (建议在 10ms 或 20ms 定时周期中调用)
 */
void 应用层全景状态机_周期执行(void)
{
    int 当前横向偏差 = 0;
    灰度路况特征_e 路况 = 扫描8路灰度传感器路面特征(&当前横向偏差);
    float 当前总里程 = 读取编码器双轮平均行驶里程_CM();
    float 当前偏航角 = 读取陀螺仪当前绝对偏航角_DEG();
    float 前方障碍距离 = 读取超声波前方障碍物距离_CM();

    小车控制上下文.小车全程累计总里程_CM = 当前总里程;
    小车控制上下文.小车当前航向偏航角_DEG = 当前偏航角;
    小车控制上下文.当前区间已驻留时间_MS += 10;

    /* 计算进入当前区间后，相对行驶的增量里程 */
    float 当前区间相对行驶里程 = 当前总里程 - 小车控制上下文.当前区间起始基准里程_CM;

    /* 全局安全保护：如果无论处于何种状态，灰度全出界且持续超过2秒，强制安全急停 */
    if (路况 == 路况_完全脱轨丢线 && 小车控制上下文.当前导航区间 != 区间_停起点驻车完成) {
        /* 此处做防抖延时累计，如果严重出界则紧急刹车 */
    }

    /* 任务4贯穿执行：时刻解算小车坐标与信标点空间几何，控制车顶指向标锁定右侧信标塔 */
    解算并更新车顶指向标瞄准信标角度(&小车控制上下文);

    /* -------------------------------------------------------------------------- */
    /*                           中层赛道导航区间状态机跳转                        */
    /* -------------------------------------------------------------------------- */
    switch (小车控制上下文.当前导航区间)
    {
        /* ---------------------------------------------------------------------- */
        /* 【区间 1】从下方右侧停起点朝左发车，顺时针进入下方直道                    */
        /* ---------------------------------------------------------------------- */
        case 区间_起点直接启动:
        {
            /* 发车后首个控制周期直接下发35% PWM目标，不执行平滑加速。 */
            设置左右双轮目标速度(目标巡航速度_PWM, 计算灰度循线PID转向纠偏量(当前横向偏差));

            /* 驶离起点超过30cm后进入下一状态。 */
            if (当前区间相对行驶里程 >= 30.0f) {
                小车控制上下文.当前导航区间 = 区间_楼梯前盲区屏蔽;
                小车控制上下文.当前区间起始基准里程_CM = 当前总里程;
            }
            break;
        }

        /* ---------------------------------------------------------------------- */
        /* 【区间 2】沿下方直道向左、左侧竖道向上，楼梯前盲区保护                    */
        /* ---------------------------------------------------------------------- */
        case 区间_楼梯前盲区屏蔽:
        {
            /* 未到左侧楼梯岔路前，不采纳右侧分支误检，执行常规循线 */
            设置左右双轮目标速度(目标巡航速度_PWM, 计算灰度循线PID转向纠偏量(当前横向偏差));

            /* 条件判断：物理里程累计接近楼梯岔路口（如达到80cm）后，才解除屏蔽，允许路口识别 */
            if (当前总里程 >= 楼梯岔路前盲区屏蔽里程_CM) {
                小车控制上下文.当前导航区间 = 区间_楼梯分岔决策口;
                小车控制上下文.当前区间起始基准里程_CM = 当前总里程;
            }
            break;
        }

        /* ---------------------------------------------------------------------- */
        /* 【区间 3】左侧竖道上行时的右侧楼梯入口 (进楼梯 vs 沿主道向上)             */
        /* ---------------------------------------------------------------------- */
        case 区间_楼梯分岔决策口:
        {
            if (小车控制上下文.当前任务 == 任务2_楼梯区域闭环跑满两圈)
            {
                /* 任务2分支：必须主动切入楼梯！ */
                /* 顺时针上行时楼梯入口在右侧；右侧探头确认支线后右转切入 */
                if (路况 == 路况_右侧有分支黑线) {
                    /* 差速接口约定：正修正量使左轮快于右轮，车体右转 */
                    设置左右双轮目标速度(目标巡航速度_PWM, +12);

                    /* 状态跳转：正式进入楼梯双圈闭环任务 */
                    小车控制上下文.当前导航区间 = 区间_楼梯环形闭环多圈;
                    小车控制上下文.当前区间起始基准里程_CM = 当前总里程;
                    小车控制上下文.楼梯子状态 = 楼梯子状态_进入后第1圈循迹;
                    小车控制上下文.楼梯已跑完圈数 = 0;
                    小车控制上下文.楼梯区间起始偏航基准角_DEG = 当前偏航角;
                    小车控制上下文.楼梯区间累计转角_DEG = 0.0f;
                    小车控制上下文.楼梯单圈起始里程_CM = 当前总里程;
                    小车控制上下文.楼梯单圈起始累计角_DEG = 0.0f;
                    小车控制上下文.楼梯计圈路标已锁存 = false;
                } else {
                    /* 还没扫到右分支时，继续贴线往前探寻 */
                    设置左右双轮目标速度(目标巡航速度_PWM, 计算灰度循线PID转向纠偏量(当前横向偏差));
                }
            }
            else
            {
                /* 任务1和任务3：沿左侧竖道向上直行，严禁右转误入楼梯 */
                /* 仅在岔路窗口压制朝右侧支线的转向修正；离开窗口后恢复双向纠偏 */
                int 修正量 = 计算灰度循线PID转向纠偏量(当前横向偏差);
                if (路况 == 路况_右侧有分支黑线 && 修正量 > 0) { 修正量 = 0; }
                设置左右双轮目标速度(目标巡航速度_PWM, 修正量);

                /* 越过右侧岔口后仍在左侧竖道，不能立即启动上方直道避障/正弦动作 */
                if (当前区间相对行驶里程 >= 楼梯岔路物理判定区间_CM) {
                    小车控制上下文.当前导航区间 = 区间_左侧主道继续上行;
                    小车控制上下文.当前区间起始基准里程_CM = 当前总里程;
                }
            }
            break;
        }

        /* ---------------------------------------------------------------------- */
        /* 【区间 4】楼梯环形闭环多圈段 (任务2核心：跑满整整两圈闭环计数)             */
        /* ---------------------------------------------------------------------- */
        case 区间_楼梯环形闭环多圈:
        {
            float 当前楼梯单圈相对里程 = 当前总里程 - 小车控制上下文.楼梯单圈起始里程_CM;
            
            /* 将IMU的±180°跳变展开为连续角度；只有新鲜有效样本才更新累计值。 */
            // 假设此处通过前后角度差更新 小车控制上下文.楼梯区间累计转角_DEG;
            if (路况 != 路况_左侧有分支黑线) {
                小车控制上下文.楼梯计圈路标已锁存 = false;
            }
            /* 超过扩展窗口仍未确认路标，不无限等待，也不能猜测已经跑完一圈。 */
            if (小车控制上下文.楼梯已跑完圈数 < 2 &&
                当前楼梯单圈相对里程 > 楼梯单圈标准周长_CM + 楼梯单圈扩展误差_CM + 20.0f) {
                小车控制上下文.当前导航区间 = 区间_定位异常安全停机;
                紧急刹车完全停机();
                break;
            }

            switch (小车控制上下文.楼梯子状态)
            {
                case 楼梯子状态_进入后第1圈循迹:
                {
                    /* 沿楼梯波浪起伏黑线平稳自适应循迹 */
                    设置左右双轮目标速度(目标巡航速度_PWM, 计算灰度循线PID转向纠偏量(当前横向偏差));

                    /* 下方岔口路标触发；本圈相对里程在窗口内，IMU新鲜时再作角度检查。 */
                    if (楼梯单圈路标可信(&小车控制上下文, 路况, 当前楼梯单圈相对里程))
                    {
                        小车控制上下文.楼梯已跑完圈数 = 1;
                        小车控制上下文.楼梯单圈起始里程_CM = 当前总里程;
                        小车控制上下文.楼梯单圈起始累计角_DEG = 小车控制上下文.楼梯区间累计转角_DEG;
                        小车控制上下文.楼梯计圈路标已锁存 = true;
                        小车控制上下文.楼梯子状态 = 楼梯子状态_第2圈循迹中;
                    }
                    break;
                }

                case 楼梯子状态_第2圈循迹中:
                {
                    设置左右双轮目标速度(目标巡航速度_PWM, 计算灰度循线PID转向纠偏量(当前横向偏差));

                    /* 使用第二圈自己的里程和转角基准，避免首圈误差传递。 */
                    if (楼梯单圈路标可信(&小车控制上下文, 路况, 当前楼梯单圈相对里程))
                    {
                        小车控制上下文.楼梯已跑完圈数 = 2;
                        小车控制上下文.楼梯计圈路标已锁存 = true;
                        /* 两圈已跑满！立即激活“寻找出路口并道”状态 */
                        小车控制上下文.楼梯子状态 = 楼梯子状态_第2圈完成确认;
                    }
                    break;
                }

                case 楼梯子状态_第2圈完成确认:
                {
                    /* 已经确认跑完两圈，沿内侧支线向西接近上方合流口，寻找右侧主干道 */
                    设置左右双轮目标速度(目标巡航速度_PWM, 计算灰度循线PID转向纠偏量(当前横向偏差));

                    /* 条件判断：右侧传感器扫到主道合流黑线 (路况_右侧有分支黑线) */
                    if (路况 == 路况_右侧有分支黑线) {
                        /* 触发右打角切出动作 */
                        小车控制上下文.楼梯子状态 = 楼梯子状态_右切并回主干道;
                    }
                    break;
                }

                case 楼梯子状态_右切并回主干道:
                {
                    /* 右转切回主干道外圈 */
                    设置左右双轮目标速度(目标巡航速度_PWM, +12);

                    /* 当中间两颗灰度探头重新对准主干道中心黑线时，说明并道成功！ */
                    if (路况 == 路况_普通直线缓弯) {
                        /* 右转回左侧竖道并继续向上，尚未到达左上弯 */
                        小车控制上下文.当前导航区间 = 区间_左侧主道继续上行;
                        小车控制上下文.当前区间起始基准里程_CM = 当前总里程;
                    }
                    break;
                }
            }
            break;
        }

        /* ---------------------------------------------------------------------- */
        /* 【区间 5】通过楼梯区域后，沿左侧主道向上，到左上弯才进入上方直道          */
        /* ---------------------------------------------------------------------- */
        case 区间_左侧主道继续上行:
        {
            设置左右双轮目标速度(目标巡航速度_PWM, 计算灰度循线PID转向纠偏量(当前横向偏差));
            /* 各任务均使用进入本路段后的相对里程，避免前面路段的误差一路累计。 */
            bool 到达左上弯 = (小车控制上下文.当前任务 == 任务2_楼梯区域闭环跑满两圈)
                ? (当前区间相对行驶里程 >= 楼梯出口至上方直道_CM)
                : (当前区间相对行驶里程 >= 楼梯岔口后至上方直道_CM);
            if (到达左上弯) {
                小车控制上下文.当前导航区间 = 区间_上方长直道;
                小车控制上下文.当前区间起始基准里程_CM = 当前总里程;
                小车控制上下文.避障子状态 = 避障子状态_直道正常循线;
                小车控制上下文.正弦摆动时间相位_RAD = 0.0f;
            }
            break;
        }

        /* ---------------------------------------------------------------------- */
        /* 【区间 6】左上弯后沿上方直道向右 (任务1避障 / 任务3正弦摆动)             */
        /* ---------------------------------------------------------------------- */
        case 区间_上方长直道:
        {
            if (小车控制上下文.当前任务 == 任务1_全程匀速循线避障)
            {
                /* 任务1：直道超声波避障状态机 */
                switch (小车控制上下文.避障子状态)
                {
                    case 避障子状态_直道正常循线:
                        设置左右双轮目标速度(目标巡航速度_PWM, 计算灰度循线PID转向纠偏量(当前横向偏差));
                        
                        /* 条件判断：超声波检测到前方障碍物持续小于 25cm */
                        if (前方障碍距离 > 0.0f && 前方障碍距离 <= 避障触发安全距离_CM) {
                            小车控制上下文.避障子状态 = 避障子状态_左打角脱线绕出;
                            小车控制上下文.避障起始偏航基准角_DEG = 当前偏航角;
                            小车控制上下文.避障起始里程_CM = 当前总里程;
                        }
                        break;

                    case 避障子状态_左打角脱线绕出:
                        /* 左偏打角，并由陀螺仪监控偏角 */
                        设置左右双轮目标速度(避障最高限制速度_PWM, -10);
                        
                        /* 条件判断：车体向左偏转达到 35° 时，摆平车身开始平行越障 */
                        if (fabs(当前偏航角 - 小车控制上下文.避障起始偏航基准角_DEG) >= 35.0f) {
                            小车控制上下文.避障子状态 = 避障子状态_平行越障前行;
                            小车控制上下文.避障起始里程_CM = 当前总里程;
                        }
                        break;

                    case 避障子状态_平行越障前行:
                        /* 回正方向直行平移，越过障碍物侧面 */
                        设置左右双轮目标速度(避障最高限制速度_PWM, 0);

                        /* 条件判断：平行前行里程达到障碍物长度 (如 35cm) */
                        if ((当前总里程 - 小车控制上下文.避障起始里程_CM) >= 35.0f) {
                            小车控制上下文.避障子状态 = 避障子状态_右打角对准回线;
                            小车控制上下文.避障起始偏航基准角_DEG = 当前偏航角;
                        }
                        break;

                    case 避障子状态_右打角对准回线:
                        /* 右切向赛道黑线切回 */
                        设置左右双轮目标速度(避障最高限制速度_PWM, +10);

                        /* 条件判断：灰度传感器再次捕获到地面黑线 */
                        if (路况 == 路况_普通直线缓弯) {
                            小车控制上下文.避障子状态 = 避障子状态_重新锁线平稳恢复;
                        }
                        break;

                    case 避障子状态_重新锁线平稳恢复:
                        /* 重新锁死中心黑线，恢复至常规匀速循线 */
                        设置左右双轮目标速度(目标巡航速度_PWM, 计算灰度循线PID转向纠偏量(当前横向偏差));
                        小车控制上下文.避障子状态 = 避障子状态_直道正常循线;
                        break;
                }
                /* 避障动作完成后才允许离开直道；继续顺时针经右侧竖道回到起点。 */
                if (当前区间相对行驶里程 >= 上方直道总长度_CM &&
                    小车控制上下文.避障子状态 == 避障子状态_直道正常循线) {
                    小车控制上下文.当前导航区间 = 区间_终点减速回站;
                    小车控制上下文.当前区间起始基准里程_CM = 当前总里程;
                }
            }
            else if (小车控制上下文.当前任务 == 任务3_上方长直道正弦摆动走直线)
            {
                /* 任务3：在直道上主动叠加连续平滑的正弦波轨迹 */
                小车控制上下文.正弦摆动时间相位_RAD += 0.08f; /* 控制摆动角频率 */
                int 正弦差速补偿量 = (int)(15.0f * sinf(小车控制上下文.正弦摆动时间相位_RAD));
                
                /* 正弦差速叠加在巡航目标上；可按循迹稳定性调整实际车速。 */
                设置左右双轮目标速度(目标巡航速度_PWM, 正弦差速补偿量);

                /* 条件判断：长直道行程即将结束时，在正弦过零点平滑退出，严防转弯时失控甩飞 */
                if (当前区间相对行驶里程 >= 上方直道总长度_CM && fabs(sinf(小车控制上下文.正弦摆动时间相位_RAD)) < 0.1f) {
                    /* 平滑切出直道 */
                    小车控制上下文.当前导航区间 = 区间_终点减速回站;
                    小车控制上下文.当前区间起始基准里程_CM = 当前总里程;
                }
            }
            else
            {
                /* 任务2等其他任务：直道常规巡线高速通过 */
                设置左右双轮目标速度(目标巡航速度_PWM, 计算灰度循线PID转向纠偏量(当前横向偏差));
                if (当前区间相对行驶里程 >= 上方直道总长度_CM) {
                    小车控制上下文.当前导航区间 = 区间_终点减速回站;
                    小车控制上下文.当前区间起始基准里程_CM = 当前总里程;
                }
            }
            break;
        }

        /* ---------------------------------------------------------------------- */
        /* 【区间 7】经右侧竖道向下、下方直道向左，回停起点的减速段                  */
        /* ---------------------------------------------------------------------- */
        case 区间_终点减速回站:
        {
            /* 距离起点越来越近，平滑过渡降速，方便精准刹停在停车框内 */
            int 进站平稳速度 = 22; 
            设置左右双轮目标速度(进站平稳速度, 计算灰度循线PID转向纠偏量(当前横向偏差));

            /* 条件判断：同时满足两项指标判定到站
             * 指标1: 小车总里程接近赛道一周物理周长 (例如 > 400cm)
             * 指标2: 8路灰度识别到起点全黑停止线 (路况_检测到全黑起终点线)
             */
            if (当前总里程 >= 减速进站准备里程门限_CM && 路况 == 路况_检测到全黑起终点线) {
                /* 立即切入驻车刹车状态 */
                小车控制上下文.当前导航区间 = 区间_停起点驻车完成;
                紧急刹车完全停机();
            }
            break;
        }

        /* ---------------------------------------------------------------------- */
        /* 【区间 8】停起点驻车完成                                                */
        /* ---------------------------------------------------------------------- */
        case 区间_停起点驻车完成:
        {
            /* 电机刹停，保持静止，屏幕展示本次任务最终用时与成绩 */
            紧急刹车完全停机();
            break;
        }

        case 区间_定位异常安全停机:
            紧急刹车完全停机();
            break;
    }

    /* -------------------------------------------------------------------------- */
    /*                           上位机无线遥测实时同步                            */
    /* -------------------------------------------------------------------------- */
    上位机无线遥测_发送运行波形与状态(
        (float)目标巡航速度_PWM,
        小车控制上下文.当前区间已驻留时间_MS,
        (uint8_t)小车控制上下文.当前任务,
        (uint8_t)小车控制上下文.当前导航区间
    );
}

