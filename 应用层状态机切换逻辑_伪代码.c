/* 路标是计圈事件；本圈相对里程和新鲜IMU角度只做合理性窗口校验。窗口需实车标定。 */
static bool 楼梯单圈路标可信(小车全景导航上下文_t *ctx, 灰度路况特征_e 路况, float 本圈里程_CM)
{
    if (ctx->楼梯计圈路标已锁存 || 路况 != 路况_左侧有分支黑线) {
        return false;
    }
    float 里程偏差 = fabsf(本圈里程_CM - 楼梯单圈标准周长_CM);
    if (!陀螺仪数据有效()) {
        return 里程偏差 <= 楼梯单圈里程允许误差_CM;
    }
    float 本圈转角 = fabsf(ctx->楼梯区间累计转角_DEG - ctx->楼梯单圈起始累计角_DEG);
    bool 航向合理 = fabsf(本圈转角 - 360.0f) <= 楼梯单圈航向允许误差_DEG;
    return 里程偏差 <= 楼梯单圈扩展误差_CM && 航向合理;
}

/**
 * @brief 循线增量/位置式转向 PID 控制
 */
static int 计算灰度循线PID转向纠偏量(int 偏差)
{
    static int 上次偏差 = 0;
    float Kp = 0.008f;
    float Kd = 0.002f;

    int 纠偏输出 = (int)(Kp * (float)偏差 + Kd * (float)(偏差 - 上次偏差));
    上次偏差 = 偏差;

    /* 转向限幅, 保护电机差速不过大 */
    if (纠偏输出 > 15)  纠偏输出 = 15;
    if (纠偏输出 < -15) 纠偏输出 = -15;

    return 纠偏输出;
}

